create table operation_initial_charges (
    id bigint generated by default as identity primary key,
    operation_id bigint not null,
    code varchar(30) not null,
    label varchar(200) not null,
    amount numeric(19,2) not null,
    currency varchar(10) not null,
    financing_mode varchar(20) not null,
    taxable boolean not null,
    constraint fk_operation_initial_charges_operation foreign key (operation_id) references loan_operations (id) on delete cascade
);

create index idx_operation_initial_charges_operation on operation_initial_charges (operation_id);

create table operation_periodic_charges (
    id bigint generated by default as identity primary key,
    operation_id bigint not null,
    code varchar(30) not null,
    label varchar(200) not null,
    charge_type varchar(20) not null,
    amount numeric(19,2),
    currency varchar(10),
    rate_percent numeric(19,4),
    rate_base varchar(30),
    frequency varchar(30) not null,
    applies_during_grace boolean not null,
    from_installment integer not null,
    to_installment integer not null,
    constraint fk_operation_periodic_charges_operation foreign key (operation_id) references loan_operations (id) on delete cascade
);

create index idx_operation_periodic_charges_operation on operation_periodic_charges (operation_id);

