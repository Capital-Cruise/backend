create table public_quote_shares (
    id bigint generated by default as identity primary key,
    operation_id bigint not null,
    share_token varchar(80) not null unique,
    is_active boolean not null,
    expires_at timestamp with time zone,
    created_at timestamp with time zone not null,
    created_by_user_id bigint not null,
    constraint fk_public_quote_shares_operation foreign key (operation_id) references loan_operations (id) on delete cascade,
    constraint fk_public_quote_shares_user foreign key (created_by_user_id) references users (id)
);

